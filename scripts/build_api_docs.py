"""Generate docs/api_reference.md from the source tree (signatures and docstrings) with a usage map.

Run from the repository root:  python scripts/build_api_docs.py
"""
import ast
import glob
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "src", "beyond_spacetime")
ORDER = ["conventions", "plotting", "symbolic", "coordinates", "diagrams", "geodesics", "tides", "embedding", "causal",
         "regular", "perturbations", "holography", "tfd", "quantum", "timereversal", "wormholes", "chronology",
         "multiverse"]


def usage(mod):
    """Return (tests, experiments) files that import the module."""
    pat = re.compile(rf"\b{mod}\b")
    out = {"tests": [], "experiments": []}
    for kind in out:
        for p in sorted(glob.glob(os.path.join(ROOT, kind, "*.py"))):
            txt = open(p, encoding="utf-8").read()
            imp = re.findall(r"^(?:from beyond_spacetime(?: import ([^\n]+)|\.(\w+) import)|import beyond_spacetime\.(\w+))", txt, re.M)
            names = set()
            for a, b, c in imp:
                names.update(x.split(" as ")[0].strip() for x in a.split(",") if x.strip())
                if b:
                    names.add(b)
                if c:
                    names.add(c)
            if mod in names:
                out[kind].append(os.path.basename(p))
    return out["tests"], out["experiments"]


def sig(fn):
    args = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({args}){ret}"


def main():
    lines = ["# API Reference", "",
             "Generated by `scripts/build_api_docs.py` from the docstrings in `src/beyond_spacetime/`. Do not edit by hand;",
             "re-run the script after changing a docstring or signature. Every public function and class is listed with its",
             "signature and docstring, and each module section names the tests and experiments that import it.", "",
             "## Modules", ""]
    for m in ORDER:
        lines.append(f"- [`{m}`](#{m})")
    lines.append("")
    for m in ORDER:
        path = os.path.join(SRC, m + ".py")
        tree = ast.parse(open(path, encoding="utf-8").read())
        doc = ast.get_docstring(tree) or ""
        tests, exps = usage(m)
        lines += [f"## {m}", "", f"Source: `src/beyond_spacetime/{m}.py`", ""]
        lines += ["```text", doc, "```", ""]
        lines.append("Tests: " + (", ".join(f"`{t}`" for t in tests) or "none directly") + "  ")
        lines.append("Experiments: " + (", ".join(f"`{e}`" for e in exps) or "none directly"))
        lines.append("")
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                lines += [f"### `{m}.{node.name}`", "", "```python", sig(node), "```", ""]
                d = ast.get_docstring(node)
                if d:
                    lines += ["```text", d, "```", ""]
            elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
                lines += [f"### class `{m}.{node.name}`", "", "```text", ast.get_docstring(node) or "", "```", ""]
                for sub in node.body:
                    if isinstance(sub, ast.FunctionDef) and (not sub.name.startswith("_") or sub.name == "__init__"):
                        lines += [f"#### `{node.name}.{sub.name}`", "", "```python", sig(sub), "```", ""]
                        d = ast.get_docstring(sub)
                        if d:
                            lines += ["```text", d, "```", ""]
    open(os.path.join(ROOT, "docs", "api_reference.md"), "w", encoding="utf-8").write("\n".join(lines).rstrip() + "\n")


if __name__ == "__main__":
    main()
